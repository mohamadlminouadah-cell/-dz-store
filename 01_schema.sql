-- ---------- 1) الجداول ----------

create table if not exists public.settings (
  id                 int primary key default 1 check (id = 1),
  store_name         text not null default 'متجري',
  tagline            text not null default '',
  logo_url           text,
  phone              text not null default '',
  whatsapp           text not null default '',      -- بصيغة دولية بدون + مثل 213550123456
  facebook           text not null default '',
  instagram          text not null default '',
  tiktok             text not null default '',
  primary_color      text not null default '#0F6B5C',
  announcement       text not null default '',
  free_shipping_min  int  not null default 0 check (free_shipping_min >= 0),  -- 0 = معطّل
  low_stock_threshold int not null default 5 check (low_stock_threshold >= 0),
  orders_open        boolean not null default true,
  updated_at         timestamptz not null default now()
);
insert into public.settings (id) values (1) on conflict do nothing;

create table if not exists public.categories (
  id      bigint generated by default as identity primary key,
  name    text not null check (char_length(trim(name)) > 0),
  sort    int  not null default 0,
  active  boolean not null default true
);

create table if not exists public.products (
  id           uuid primary key default gen_random_uuid(),
  name         text not null check (char_length(trim(name)) > 0),
  description  text not null default '',
  price        int  not null check (price >= 0),
  old_price    int  check (old_price is null or old_price > price),
  category_id  bigint references public.categories(id) on delete set null,
  images       text[] not null default '{}',
  colors       text[] not null default '{}',
  sizes        text[] not null default '{}',
  stock        int  not null default 0 check (stock >= 0),      -- الكمية الفعلية بعد خصم الطلبات المؤكدة
  reserved     int  not null default 0 check (reserved >= 0),   -- كمية محجوزة لطلبات جديدة لم تؤكد بعد
  status       text not null default 'available'
               check (status in ('available','unavailable','hidden')),
  featured     boolean not null default false,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);
create index if not exists products_category_idx on public.products(category_id);

-- سعر التكلفة في جدول منفصل حتى لا يراه الزبائن أبداً
create table if not exists public.product_costs (
  product_id uuid primary key references public.products(id) on delete cascade,
  cost       int not null default 0 check (cost >= 0)
);

create table if not exists public.communes (
  id          int primary key,
  wilaya_code smallint not null check (wilaya_code between 1 and 58),
  name        text not null
);
create index if not exists communes_wilaya_idx on public.communes(wilaya_code);

create table if not exists public.delivery_rates (
  wilaya_code smallint primary key check (wilaya_code between 1 and 58),
  wilaya_name text not null,
  home_fee    int  not null default 0 check (home_fee >= 0),
  desk_fee    int  check (desk_fee is null or desk_fee >= 0),   -- NULL = لا يوجد استلام من المكتب
  enabled     boolean not null default true                      -- false = لا نوصّل لهذه الولاية
);

create table if not exists public.commune_rates (
  commune_id  int primary key references public.communes(id) on delete cascade,
  home_fee    int not null check (home_fee >= 0)
);

create table if not exists public.coupons (
  code        text primary key check (code = upper(code) and char_length(code) between 2 and 30),
  kind        text not null check (kind in ('percent','fixed')),
  value       int  not null check (value > 0),
  min_total   int  not null default 0 check (min_total >= 0),
  active      boolean not null default true,
  max_uses    int  check (max_uses is null or max_uses > 0),
  used        int  not null default 0,
  expires_at  timestamptz
);

create sequence if not exists public.order_seq;

create table if not exists public.orders (
  id             bigint generated by default as identity primary key,
  order_number   text not null unique,
  customer_name  text not null,
  phone          text not null,
  wilaya_code    smallint not null,
  wilaya_name    text not null,
  commune_id     int not null,
  commune_name   text not null,
  address        text not null default '',
  notes          text not null default '',
  delivery_type  text not null check (delivery_type in ('home','desk')),
  subtotal       int not null,
  delivery_fee   int not null,
  discount       int not null default 0,
  coupon_code    text,
  total          int not null,
  status         text not null default 'new'
                 check (status in ('new','confirming','confirmed','preparing','shipped','delivered','cancelled','returned')),
  -- حالة المخزون لهذا الطلب: reserved = محجوز فقط، deducted = خُصم من المخزون، released = أُرجع/أُلغي
  stock_state    text not null default 'reserved' check (stock_state in ('reserved','deducted','released')),
  admin_notes    text not null default '',
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);
create index if not exists orders_created_idx on public.orders(created_at desc);
create index if not exists orders_phone_idx   on public.orders(phone);

create table if not exists public.order_items (
  id            bigint generated by default as identity primary key,
  order_id      bigint not null references public.orders(id) on delete cascade,
  product_id    uuid references public.products(id) on delete set null,
  product_name  text not null,
  options       text,
  unit_price    int not null,
  unit_cost     int not null default 0,
  quantity      int not null check (quantity > 0)
);
create index if not exists order_items_order_idx on public.order_items(order_id);

-- المديرون: حسابات Supabase Auth المسموح لها بدخول لوحة الإدارة
create table if not exists public.admin_users (
  user_id    uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

