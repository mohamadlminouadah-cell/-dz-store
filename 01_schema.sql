-- ---------- 4) حساب السعر (مصدر الحقيقة الوحيد: الخادم) ----------
-- رسائل الأخطاء تبدأ برمز ثم | ثم تفاصيل، والواجهة تترجمها للعربية.

create or replace function public._compute_quote(
  p_items jsonb, p_wilaya int, p_commune int, p_delivery text, p_coupon text, p_need_delivery boolean
) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  it jsonb; pr public.products; q numeric; v_color text; v_size text;
  v_sub int := 0; v_lines jsonb := '[]'::jsonb; r record;
  s public.settings; dr public.delivery_rates;
  v_fee int := 0; v_free boolean := false; v_pending boolean := false;
  v_wname text; v_cname text; v_dtype text := coalesce(nullif(p_delivery,''), 'home');
  cp public.coupons; v_disc int := 0; v_code text;
begin
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'EMPTY_CART|';
  end if;
  if jsonb_array_length(p_items) > 30 then raise exception 'CART_TOO_LARGE|'; end if;
  select * into s from settings where id = 1;

  for it in select value from jsonb_array_elements(p_items) loop
    if jsonb_typeof(it->'qty') <> 'number' or jsonb_typeof(it->'id') <> 'string' then
      raise exception 'BAD_ITEM|';
    end if;
    q := (it->>'qty')::numeric;
    if q <> trunc(q) or q < 1 or q > 100 then raise exception 'BAD_QTY|'; end if;

    select * into pr from products where id = (it->>'id')::uuid;
    if not found or pr.status <> 'available' then
      raise exception 'PRODUCT_UNAVAILABLE|%', coalesce(pr.name, '');
    end if;

    v_color := nullif(trim(coalesce(it->>'color','')), '');
    v_size  := nullif(trim(coalesce(it->>'size','')), '');
    if coalesce(array_length(pr.colors,1),0) > 0 then
      if v_color is null or not (v_color = any(pr.colors)) then raise exception 'OPTION_REQUIRED|%', pr.name; end if;
    else v_color := null; end if;
    if coalesce(array_length(pr.sizes,1),0) > 0 then
      if v_size is null or not (v_size = any(pr.sizes)) then raise exception 'OPTION_REQUIRED|%', pr.name; end if;
    else v_size := null; end if;

    v_lines := v_lines || jsonb_build_object(
      'id', pr.id, 'name', pr.name, 'price', pr.price, 'qty', q::int,
      'color', v_color, 'size', v_size, 'line_total', pr.price * q::int, 'image', pr.images[1]);
    v_sub := v_sub + pr.price * q::int;
  end loop;

  -- المخزون: المجموع لكل منتج (قد يظهر نفس المنتج بخيارات مختلفة)
  for r in
    select (l->>'id')::uuid as pid, sum((l->>'qty')::int) as q
    from jsonb_array_elements(v_lines) l group by 1
  loop
    select * into pr from products where id = r.pid;
    if pr.stock - pr.reserved < r.q then
      raise exception 'INSUFFICIENT_STOCK|%|%', pr.name, greatest(pr.stock - pr.reserved, 0);
    end if;
  end loop;

  -- التوصيل
  if p_wilaya is null then
    if p_need_delivery then raise exception 'NO_DELIVERY|'; end if;
    v_pending := true;
  else
    select * into dr from delivery_rates where wilaya_code = p_wilaya;
    if not found or not dr.enabled then raise exception 'NO_DELIVERY|'; end if;
    v_wname := dr.wilaya_name;
    if p_commune is null then
      if p_need_delivery then raise exception 'BAD_COMMUNE|'; end if;
    else
      select name into v_cname from communes where id = p_commune and wilaya_code = p_wilaya;
      if not found then raise exception 'BAD_COMMUNE|'; end if;
    end if;
    if v_dtype = 'desk' then
      if dr.desk_fee is null then raise exception 'NO_DESK|'; end if;
      v_fee := dr.desk_fee;
    elsif v_dtype = 'home' then
      v_fee := coalesce((select home_fee from commune_rates where commune_id = p_commune), dr.home_fee);
    else
      raise exception 'BAD_DELIVERY|';
    end if;
    if s.free_shipping_min > 0 and v_sub >= s.free_shipping_min then v_fee := 0; v_free := true; end if;
  end if;

  -- الكوبون
  v_code := upper(trim(coalesce(p_coupon, '')));
  if v_code <> '' then
    select * into cp from coupons where code = v_code;
    if not found or not cp.active
       or (cp.expires_at is not null and cp.expires_at < now())
       or (cp.max_uses is not null and cp.used >= cp.max_uses)
       or v_sub < cp.min_total then
      raise exception 'BAD_COUPON|';
    end if;
    v_disc := case cp.kind when 'percent' then (v_sub * least(cp.value, 100)) / 100
                           else least(cp.value, v_sub) end;
  else
    v_code := null;
  end if;

  return jsonb_build_object(
    'lines', v_lines, 'subtotal', v_sub, 'delivery_fee', v_fee, 'free_shipping', v_free,
    'delivery_pending', v_pending, 'discount', v_disc, 'coupon', v_code,
    'total', v_sub - v_disc + v_fee, 'wilaya_name', v_wname, 'commune_name', v_cname,
    'delivery_type', v_dtype);
end $$;

-- للواجهة: معاينة السعر قبل التأكيد
create or replace function public.quote_order(
  p_items jsonb, p_wilaya int default null, p_commune int default null,
  p_delivery text default 'home', p_coupon text default null
) returns jsonb language sql security definer set search_path = public as $$
  select public._compute_quote(p_items, p_wilaya, p_commune, p_delivery, p_coupon, false);
$$;

-- ---------- 5) إنشاء الطلب ----------

create or replace function public.create_order(p jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  s public.settings; q jsonb; v_name text; v_phone text; v_addr text; v_notes text;
  v_dtype text; v_id bigint; v_num text; v_wilaya int; v_commune int;
begin
  if p is null or jsonb_typeof(p) <> 'object' then raise exception 'BAD_REQUEST|'; end if;
  select * into s from settings where id = 1;
  if not s.orders_open then raise exception 'ORDERS_CLOSED|'; end if;
  if nullif(trim(coalesce(p->>'hp','')), '') is not null then raise exception 'BAD_REQUEST|'; end if; -- فخ البوتات
  if jsonb_typeof(p->'items') <> 'array' or jsonb_array_length(p->'items') = 0 then raise exception 'EMPTY_CART|'; end if;

  v_name := regexp_replace(trim(coalesce(p->>'name','')), '\s+', ' ', 'g');
  if char_length(v_name) < 2 or char_length(v_name) > 80 then raise exception 'BAD_NAME|'; end if;

  -- توحيد رقم الهاتف: +213 / 00213 → 0
  v_phone := regexp_replace(coalesce(p->>'phone',''), '[\s\.\-\(\)]', '', 'g');
  v_phone := regexp_replace(v_phone, '^(\+213|00213|213)', '0');
  if v_phone !~ '^0[567][0-9]{8}$' and v_phone !~ '^0[234][0-9]{7,8}$' then raise exception 'BAD_PHONE|'; end if;

  v_dtype := coalesce(nullif(p->>'delivery_type',''), 'home');
  v_addr  := trim(coalesce(p->>'address',''));
  v_notes := trim(coalesce(p->>'notes',''));
  if v_dtype = 'home' and char_length(v_addr) < 4 then raise exception 'BAD_ADDRESS|'; end if;
  if char_length(v_addr) > 300 or char_length(v_notes) > 500 then raise exception 'TOO_LONG|'; end if;

  if (select count(*) from orders where phone = v_phone and created_at > now() - interval '1 hour') >= 5 then
    raise exception 'TOO_MANY|';
  end if;

  if jsonb_typeof(p->'wilaya') <> 'number' or jsonb_typeof(p->'commune') <> 'number' then raise exception 'BAD_COMMUNE|'; end if;
  v_wilaya  := (p->>'wilaya')::int;
  v_commune := (p->>'commune')::int;

  -- قفل صفوف المنتجات لمنع بيع نفس الكمية لشخصين في نفس اللحظة
  perform 1 from products
   where id in (select (x->>'id')::uuid from jsonb_array_elements(p->'items') x)
   order by id for update;

  q := public._compute_quote(p->'items', v_wilaya, v_commune, v_dtype, p->>'coupon', true);

  v_num := to_char(now() at time zone 'Africa/Algiers', 'YYMMDD') || '-' || lpad(nextval('public.order_seq')::text, 4, '0');

  insert into orders (order_number, customer_name, phone, wilaya_code, wilaya_name, commune_id, commune_name,
                      address, notes, delivery_type, subtotal, delivery_fee, discount, coupon_code, total)
  values (v_num, v_name, v_phone, v_wilaya, q->>'wilaya_name', v_commune, q->>'commune_name',
          v_addr, v_notes, v_dtype, (q->>'subtotal')::int, (q->>'delivery_fee')::int,
          (q->>'discount')::int, q->>'coupon', (q->>'total')::int)
  returning id into v_id;

  insert into order_items (order_id, product_id, product_name, options, unit_price, unit_cost, quantity)
  select v_id, (l->>'id')::uuid, l->>'name',
         nullif(concat_ws('، ',
           case when l->>'color' is not null then 'اللون: ' || (l->>'color') end,
           case when l->>'size'  is not null then 'المقاس: ' || (l->>'size') end), ''),
         (l->>'price')::int, coalesce(pc.cost, 0), (l->>'qty')::int
  from jsonb_array_elements(q->'lines') l
  left join product_costs pc on pc.product_id = (l->>'id')::uuid;

  -- حجز الكمية (تُخصم فعلياً عند "تم التأكيد")
  update products pr set reserved = pr.reserved + s2.q
  from (select (l->>'id')::uuid as pid, sum((l->>'qty')::int) as q
        from jsonb_array_elements(q->'lines') l group by 1) s2
  where pr.id = s2.pid;

  if q->>'coupon' is not null then
    update coupons set used = used + 1 where code = q->>'coupon';
  end if;

  return jsonb_build_object('order_number', v_num, 'subtotal', (q->>'subtotal')::int,
    'delivery_fee', (q->>'delivery_fee')::int, 'discount', (q->>'discount')::int, 'total', (q->>'total')::int);
end $$;

-- تتبع الطلب برقم الطلب + رقم الهاتف
create or replace function public.track_order(p_number text, p_phone text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare o public.orders; v_phone text;
begin
  v_phone := regexp_replace(coalesce(p_phone,''), '[\s\.\-\(\)]', '', 'g');
  v_phone := regexp_replace(v_phone, '^(\+213|00213|213)', '0');
  select * into o from orders where order_number = upper(trim(coalesce(p_number,''))) and phone = v_phone;
  if not found then return null; end if;
  return jsonb_build_object('order_number', o.order_number, 'status', o.status, 'total', o.total,
    'created_at', o.created_at, 'wilaya_name', o.wilaya_name, 'commune_name', o.commune_name,
    'items', coalesce((select jsonb_agg(jsonb_build_object('name', i.product_name, 'options', i.options, 'qty', i.quantity, 'price', i.unit_price))
                       from order_items i where i.order_id = o.id), '[]'::jsonb));
end $$;

-- ---------- 6) دوال المدير ----------

-- تغيير حالة الطلب مع إدارة المخزون بدون احتساب مزدوج:
--   جديد / قيد التأكيد              → الكمية "محجوزة"
--   تم التأكيد / التجهيز / الشحن / التسليم → الكمية "مخصومة" من المخزون
--   ملغى / مرتجع                    → الكمية تعود للمخزون
create or replace function public.admin_set_order_status(p_id bigint, p_status text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare o public.orders; v_target text; r record;
begin
  if not public.is_admin() then raise exception 'FORBIDDEN|'; end if;
  if p_status not in ('new','confirming','confirmed','preparing','shipped','delivered','cancelled','returned') then
    raise exception 'BAD_STATUS|';
  end if;
  select * into o from orders where id = p_id for update;
  if not found then raise exception 'NOT_FOUND|'; end if;

  v_target := case when p_status in ('new','confirming') then 'reserved'
                   when p_status in ('confirmed','preparing','shipped','delivered') then 'deducted'
                   else 'released' end;

  if o.stock_state <> v_target then
    perform 1 from products where id in (select product_id from order_items where order_id = p_id and product_id is not null)
      order by id for update;

    -- 1) تراجع عن الأثر السابق
    if o.stock_state = 'reserved' then
      update products pr set reserved = greatest(pr.reserved - s.q, 0)
      from (select product_id, sum(quantity) q from order_items where order_id = p_id and product_id is not null group by 1) s
      where pr.id = s.product_id;
    elsif o.stock_state = 'deducted' then
      update products pr set stock = pr.stock + s.q
      from (select product_id, sum(quantity) q from order_items where order_id = p_id and product_id is not null group by 1) s
      where pr.id = s.product_id;
    end if;

    -- 2) طبّق الأثر الجديد بعد التأكد من توفر الكمية
    if v_target in ('reserved','deducted') then
      for r in select i.product_id, sum(i.quantity) q, max(pr.name) nm, max(pr.stock - pr.reserved) av
               from order_items i join products pr on pr.id = i.product_id
               where i.order_id = p_id group by 1 loop
        if r.av < r.q then raise exception 'INSUFFICIENT_STOCK|%|%', r.nm, greatest(r.av, 0); end if;
      end loop;
      if v_target = 'reserved' then
        update products pr set reserved = pr.reserved + s.q
        from (select product_id, sum(quantity) q from order_items where order_id = p_id and product_id is not null group by 1) s
        where pr.id = s.product_id;
      else
        update products pr set stock = pr.stock - s.q
        from (select product_id, sum(quantity) q from order_items where order_id = p_id and product_id is not null group by 1) s
        where pr.id = s.product_id;
      end if;
    end if;
  end if;

  update orders set status = p_status, stock_state = v_target, updated_at = now() where id = p_id;
  return jsonb_build_object('id', p_id, 'status', p_status, 'stock_state', v_target);
end $$;

-- حذف طلب (مثلاً طلب تجريبي) مع إرجاع المخزون أولاً
create or replace function public.admin_delete_order(p_id bigint)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'FORBIDDEN|'; end if;
  perform public.admin_set_order_status(p_id, 'cancelled');
  delete from orders where id = p_id;
end $$;

-- الإحصائيات: المبيعات المكتملة = الطلبات "تم التسليم" فقط
create or replace function public.admin_stats(p_from date, p_to date)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v jsonb; t0 timestamptz; t1 timestamptz;
begin
  if not public.is_admin() then raise exception 'FORBIDDEN|'; end if;
  t0 := p_from::timestamp at time zone 'Africa/Algiers';
  t1 := (p_to + 1)::timestamp at time zone 'Africa/Algiers';
  with o as (select * from orders where created_at >= t0 and created_at < t1)
  select jsonb_build_object(
    'orders_total', (select count(*) from o),
    'by_status', coalesce((select jsonb_object_agg(status, c) from (select status, count(*) c from o group by 1) x), '{}'::jsonb),
    'delivered_count', (select count(*) from o where status = 'delivered'),
    'revenue', coalesce((select sum(subtotal - discount) from o where status = 'delivered'), 0),
    'delivery_fees', coalesce((select sum(delivery_fee) from o where status = 'delivered'), 0),
    'cost', coalesce((select sum(i.unit_cost * i.quantity) from order_items i join o on o.id = i.order_id where o.status = 'delivered'), 0),
    'missing_cost', (select count(*) from order_items i join o on o.id = i.order_id where o.status = 'delivered' and i.unit_cost = 0),
    'pending_value', coalesce((select sum(total) from o where status in ('new','confirming','confirmed','preparing','shipped')), 0),
    'top', coalesce((select jsonb_agg(t) from (
        select i.product_name as name, sum(i.quantity)::int as qty, sum(i.unit_price * i.quantity)::int as revenue
        from order_items i join o on o.id = i.order_id where o.status = 'delivered'
        group by 1 order by 2 desc, 3 desc limit 10) t), '[]'::jsonb),
    'daily', coalesce((select jsonb_agg(d order by d.day) from (
        select (o.created_at at time zone 'Africa/Algiers')::date as day, count(*)::int as orders,
               coalesce(sum(o.subtotal - o.discount) filter (where o.status = 'delivered'), 0)::int as revenue
        from o group by 1) d), '[]'::jsonb)
  ) into v;
  return v;
end $$;

-- بعد استعادة نسخة احتياطية: إعادة ضبط عدادات الأرقام التلقائية
create or replace function public.admin_resync_sequences()
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'FORBIDDEN|'; end if;
  perform setval(pg_get_serial_sequence('public.categories','id'), greatest((select coalesce(max(id),0) from categories), 1), (select count(*) > 0 from categories));
  perform setval(pg_get_serial_sequence('public.orders','id'),     greatest((select coalesce(max(id),0) from orders), 1),     (select count(*) > 0 from orders));
  perform setval(pg_get_serial_sequence('public.order_items','id'),greatest((select coalesce(max(id),0) from order_items), 1),(select count(*) > 0 from order_items));
  perform setval('public.order_seq', greatest((select count(*) from orders), 1) + 1000, true);
end $$;

